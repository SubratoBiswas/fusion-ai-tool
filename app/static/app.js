/* FusionTrials frontend — vanilla JS single-page app */

const $ = (sel) => document.querySelector(sel);
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

async function api(path, opts = {}) {
  const res = await fetch(path, {
    headers: { "Content-Type": "application/json" },
    ...opts,
  });
  if (!res.ok) {
    const body = await res.json().catch(() => ({}));
    throw new Error(body.detail || `Request failed (${res.status})`);
  }
  return res.json();
}

function spinner(el, msg = "Working — AI requests can take a minute…") {
  el.innerHTML = `<div class="spinner">⟳ ${esc(msg)}</div>`;
}
function showError(el, err) {
  el.innerHTML = `<div class="error-box">${esc(err.message || err)}</div>`;
}
function genBadge(by) {
  return `<div class="gen-by">generated by: ${esc(by || "n/a")}</div>`;
}

/* ---------- Tabs ---------- */
document.querySelectorAll(".tab").forEach((btn) => {
  btn.addEventListener("click", () => {
    document.querySelectorAll(".tab").forEach((b) => b.classList.remove("active"));
    document.querySelectorAll(".panel").forEach((p) => p.classList.remove("active"));
    btn.classList.add("active");
    $(`#panel-${btn.dataset.tab}`).classList.add("active");
  });
});

/* ---------- Dashboard ---------- */
function statusPill(status) {
  const s = (status || "").toLowerCase();
  if (s.includes("enroll")) return `<span class="pill green">${esc(status)}</span>`;
  if (s.includes("withdraw") || s.includes("fail") || s.includes("terminated")) return `<span class="pill red">${esc(status)}</span>`;
  if (s.includes("complete")) return `<span class="pill dim">${esc(status)}</span>`;
  return `<span class="pill amber">${esc(status)}</span>`;
}

async function loadDashboard() {
  try {
    const data = await api("/api/dashboard");
    const badge = $("#ai-badge");
    badge.textContent = data.ai_enabled ? "AI: Claude connected" : "AI: offline mode";
    badge.className = "ai-badge " + (data.ai_enabled ? "on" : "off");

    const t = data.totals;
    $("#kpis").innerHTML = [
      [t.studies, "Active studies"],
      [t.sites, "Sites"],
      [t.participants, "Participants enrolled"],
      [t.saes, "Serious adverse events"],
      [t.open_queries, "Open data queries"],
    ].map(([n, l]) => `<div class="kpi"><div class="num">${n}</div><div class="lbl">${l}</div></div>`).join("");

    $("#study-cards").innerHTML = data.studies.map((s) => {
      const pct = Math.min(100, Math.round((s.enrolled / s.target_enrollment) * 100));
      return `<div class="card study-card" data-id="${s.id}">
        <div class="proto">${esc(s.protocol_id)}</div>
        <h3>${esc(s.title)}</h3>
        <div class="meta-row">
          <span>${esc(s.phase)}</span><span>${esc(s.therapeutic_area)}</span>
          ${statusPill(s.status)}
        </div>
        <div class="meta-row">
          <span>${s.enrolled}/${s.target_enrollment} enrolled (${pct}%)</span>
          <span>${s.site_count} sites</span>
          <span>${s.ae_count} AEs (${s.sae_count} serious)</span>
          <span>${s.open_queries} open queries</span>
        </div>
        <div class="bar"><span style="width:${pct}%"></span></div>
      </div>`;
    }).join("");

    document.querySelectorAll(".study-card").forEach((c) =>
      c.addEventListener("click", () => loadStudyDetail(c.dataset.id)));

    // populate data-quality study selector
    $("#quality-study").innerHTML = data.studies
      .map((s) => `<option value="${s.id}">${esc(s.protocol_id)} — ${esc(s.title)}</option>`)
      .join("");
  } catch (err) {
    showError($("#kpis"), err);
  }
}

async function loadStudyDetail(id) {
  const el = $("#study-detail");
  spinner(el, "Loading study…");
  try {
    const d = await api(`/api/studies/${id}`);
    el.innerHTML = `<div class="card">
      <h3>${esc(d.study.protocol_id)} — Participants</h3>
      <table><tr><th>Subject</th><th>Site</th><th>Age</th><th>Sex</th><th>Status</th></tr>
      ${d.participants.map((p) => `<tr>
        <td class="mono">${esc(p.subject_code)}</td><td>${esc(p.site_name)}</td>
        <td>${p.age ?? "<span class='pill red'>missing</span>"}</td>
        <td>${esc(p.sex ?? "—")}</td><td>${statusPill(p.status)}</td></tr>`).join("")}
      </table>
      <h3>Adverse events</h3>
      <table><tr><th>Subject</th><th>Verbatim</th><th>Coded term</th><th>Severity</th><th>Serious</th><th>Outcome</th></tr>
      ${d.adverse_events.map((a) => `<tr>
        <td class="mono">${esc(a.subject_code)}</td><td>${esc(a.verbatim_term)}</td>
        <td>${a.preferred_term ? esc(a.preferred_term) : "<span class='pill amber'>uncoded</span>"}</td>
        <td>${esc(a.severity)}</td>
        <td>${a.serious ? "<span class='pill red'>SAE</span>" : "—"}</td>
        <td>${esc(a.outcome ?? "—")}</td></tr>`).join("")}
      </table>
      ${d.queries.length ? `<h3>Data queries</h3>
      <table><tr><th>Field</th><th>Issue</th><th>Severity</th><th>Status</th></tr>
      ${d.queries.map((q) => `<tr><td class="mono">${esc(q.field)}</td><td>${esc(q.issue)}</td>
        <td><span class="pill ${q.severity === "critical" ? "red" : q.severity === "major" ? "amber" : "dim"}">${esc(q.severity)}</span></td>
        <td>${esc(q.status)}</td></tr>`).join("")}</table>` : ""}
    </div>`;
    el.scrollIntoView({ behavior: "smooth" });
  } catch (err) { showError(el, err); }
}

/* ---------- Protocol Designer ---------- */
$("#protocol-form").addEventListener("submit", async (e) => {
  e.preventDefault();
  const out = $("#protocol-result");
  const btn = e.target.querySelector("button");
  btn.disabled = true;
  spinner(out, "Drafting protocol synopsis — this can take a minute with AI enabled…");
  try {
    const fd = new FormData(e.target);
    const body = Object.fromEntries(fd.entries());
    const p = await api("/api/ai/protocol", { method: "POST", body: JSON.stringify(body) });
    out.innerHTML = `<div class="card">
      <h3>${esc(p.title)}</h3>
      <div class="proto-section"><h4>Background</h4><p>${esc(p.background)}</p></div>
      <div class="proto-section"><h4>Objectives</h4>
        <p><strong>Primary:</strong> ${esc(p.objectives.primary)}</p>
        <ul>${p.objectives.secondary.map((s) => `<li>${esc(s)}</li>`).join("")}</ul></div>
      <div class="proto-section"><h4>Design</h4>
        <p>${esc(p.design.type)} · ${esc(p.design.blinding)} · ${esc(p.design.randomization)}</p>
        <p><strong>Duration:</strong> ${esc(p.design.duration)}</p>
        <p><strong>Arms:</strong></p><ul>${p.design.arms.map((a) => `<li>${esc(a)}</li>`).join("")}</ul></div>
      <div class="proto-section"><h4>Inclusion criteria</h4>
        <ul>${p.population.inclusion_criteria.map((c) => `<li>${esc(c)}</li>`).join("")}</ul></div>
      <div class="proto-section"><h4>Exclusion criteria</h4>
        <ul>${p.population.exclusion_criteria.map((c) => `<li>${esc(c)}</li>`).join("")}</ul></div>
      <div class="proto-section"><h4>Sample size</h4><p>${esc(p.population.sample_size_rationale)}</p></div>
      <div class="proto-section"><h4>Endpoints</h4>
        <p><strong>Primary:</strong></p><ul>${p.endpoints.primary.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>
        <p><strong>Secondary:</strong></p><ul>${p.endpoints.secondary.map((x) => `<li>${esc(x)}</li>`).join("")}</ul></div>
      <div class="proto-section"><h4>Statistical considerations</h4><p>${esc(p.statistical_considerations)}</p></div>
      <div class="proto-section"><h4>Safety monitoring</h4><p>${esc(p.safety_monitoring)}</p></div>
      ${genBadge(p._generated_by)}
    </div>`;
  } catch (err) { showError(out, err); }
  btn.disabled = false;
});

/* ---------- Eligibility ---------- */
$("#eligibility-form").addEventListener("submit", async (e) => {
  e.preventDefault();
  const out = $("#eligibility-result");
  const btn = e.target.querySelector("button");
  btn.disabled = true;
  spinner(out, "Screening patient against criteria…");
  try {
    const fd = new FormData(e.target);
    const lines = (v) => v.split("\n").map((s) => s.trim()).filter(Boolean);
    const body = {
      patient_profile: fd.get("patient_profile"),
      inclusion_criteria: lines(fd.get("inclusion")),
      exclusion_criteria: lines(fd.get("exclusion") || ""),
    };
    const r = await api("/api/ai/eligibility", { method: "POST", body: JSON.stringify(body) });
    const overallPill = r.overall === "likely_eligible" ? "green" : r.overall === "likely_ineligible" ? "red" : "amber";
    out.innerHTML = `<div class="card">
      <p><span class="pill ${overallPill}">${esc(r.overall.replace(/_/g, " "))}</span></p>
      <div class="narrative">${esc(r.summary)}</div>
      <table><tr><th>Criterion</th><th>Type</th><th>Verdict</th><th>Rationale</th></tr>
      ${r.assessments.map((a) => `<tr>
        <td>${esc(a.criterion)}</td><td>${esc(a.criterion_type)}</td>
        <td class="verdict-${esc(a.verdict)}">${esc(a.verdict.replace(/_/g, " "))}</td>
        <td>${esc(a.rationale)}</td></tr>`).join("")}
      </table>
      ${r.missing_information.length ? `<h3>Missing information</h3><ul>${r.missing_information.map((m) => `<li>${esc(m)}</li>`).join("")}</ul>` : ""}
      ${genBadge(r._generated_by)}
    </div>`;
  } catch (err) { showError(out, err); }
  btn.disabled = false;
});

