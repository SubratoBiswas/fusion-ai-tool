/* ---------- Dashboard ---------- */
function statusPill(status) {
  const s = (status || "").toLowerCase();
  if (s.includes("enroll")) return `<span class="pill green">${esc(status)}</span>`;
  if (s.includes("withdraw") || s.includes("fail") || s.includes("terminated")) return `<span class="pill red">${esc(status)}</span>`;
  if (s.includes("complete")) return `<span class="pill dim">${esc(status)}</span>`;
  return `<span class="pill amber">${esc(status)}</span>`;
}

async function loadDashboard() {
  try {
    const data = await api("/api/dashboard");
    const badge = $("#ai-badge");
    badge.textContent = data.ai_enabled ? "AI: Claude connected" : "AI: offline mode";
    badge.className = "ai-badge " + (data.ai_enabled ? "on" : "off");

    const t = data.totals;
    $("#kpis").innerHTML = [
      [t.studies, "Active studies"],
      [t.sites, "Sites"],
      [t.participants, "Participants enrolled"],
      [t.saes, "Serious adverse events"],
      [t.open_queries, "Open data queries"],
      [t.pro_alerts, "ePRO symptom alerts"],
    ].map(([n, l]) => `<div class="kpi"><div class="num">${n}</div><div class="lbl">${l}</div></div>`).join("");

    $("#study-cards").innerHTML = data.studies.map((s) => {
      const pct = Math.min(100, Math.round((s.enrolled / s.target_enrollment) * 100));
      return `<div class="card study-card" data-id="${s.id}">
        <div class="proto">${esc(s.protocol_id)}</div>
        <h3>${esc(s.title)}</h3>
        <div class="meta-row">
          <span>${esc(s.phase)}</span><span>${esc(s.therapeutic_area)}</span>
          ${statusPill(s.status)}
        </div>
        <div class="meta-row">
          <span>${s.enrolled}/${s.target_enrollment} enrolled (${pct}%)</span>
          <span>${s.site_count} sites</span>
          <span>${s.ae_count} AEs (${s.sae_count} serious)</span>
          <span>${s.open_queries} open queries</span>
        </div>
        <div class="bar"><span style="width:${pct}%"></span></div>
      </div>`;
    }).join("");

    document.querySelectorAll(".study-card").forEach((c) =>
      c.addEventListener("click", () => loadStudyDetail(c.dataset.id)));

    // populate every study selector (data quality + EDC/RTSM/ePRO/eTMF)
    studiesCache = data.studies;
    const options = data.studies
      .map((s) => `<option value="${s.id}">${esc(s.protocol_id)} — ${esc(s.title)}</option>`)
      .join("");
    document.querySelectorAll("select.study-select").forEach((sel) => {
      const prev = sel.value;
      sel.innerHTML = options;
      if (prev) sel.value = prev;
    });
    $("#quality-study").innerHTML = options;
    initModulesOnce();
  } catch (err) {
    showError($("#kpis"), err);
  }
}

let studiesCache = [];
const participantsCache = {};

async function participantsFor(studyId, { activeOnly = true } = {}) {
  if (!participantsCache[studyId]) {
    const d = await api(`/api/studies/${studyId}`);
    participantsCache[studyId] = d.participants;
  }
  const all = participantsCache[studyId];
  return activeOnly ? all.filter((p) => !["Screen Failure", "Withdrawn"].includes(p.status)) : all;
}

function invalidateParticipants(studyId) { delete participantsCache[studyId]; }

