/* FusionTrials frontend — vanilla JS single-page app */

const $ = (sel) => document.querySelector(sel);
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

async function api(path, opts = {}) {
  const res = await fetch(path, {
    headers: { "Content-Type": "application/json" },
    ...opts,
  });
  if (!res.ok) {
    const body = await res.json().catch(() => ({}));
    throw new Error(body.detail || `Request failed (${res.status})`);
  }
  return res.json();
}

function spinner(el, msg = "Working — AI requests can take a minute…") {
  el.innerHTML = `<div class="spinner">⟳ ${esc(msg)}</div>`;
}
function showError(el, err) {
  el.innerHTML = `<div class="error-box">${esc(err.message || err)}</div>`;
}
function genBadge(by) {
  return `<div class="gen-by">generated by: ${esc(by || "n/a")}</div>`;
}

